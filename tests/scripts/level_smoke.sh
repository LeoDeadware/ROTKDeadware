#!/bin/bash
# Smoke of one level (PLAYBOOK phase 4, PIT-L03: every level is the lifter's test).
#   tests/scripts/level_smoke.sh <Level> [gameplay_frames]      e.g. Pat01 4500
#   SOAK=1 tests/scripts/level_smoke.sh <Level> 60000           soak (>= 60k frames)
#
# Route (decompiled, docs/handoff/qa.md): START at the title -> intro movie -> Helm's Deep
# prologue in play from ~frame 6400; at ROUTE_AT the hook does what the scene-select menu
# does (FUN_00107EC0 case 3): character 0x16D584 = <char>, FUN_0009D770(<index>) sets the
# level index 0x16D554, FUN_0009C8A0(0) queues Data\Game\<Dir>\<Level>.scx; the game then
# plays the level's movie and loads it. Then scripted input (move, turn, attacks; never
# START = pause) for <gameplay_frames> frames.
# Asserts: exit 0, no FATAL / dispatch miss, the level's .scx opened after the call and
# gameplay draws for most of the rest (level_check.py), frames differ near the end.
source "$(dirname "$0")/../lib.sh"
LEVEL="${1:?level, e.g. Pat01}"
PLAY="${2:-4500}"
ROUTE_AT="${ROUTE_AT:-6800}"
LOAD_FRAMES="${LOAD_FRAMES:-4000}"   # level movie + loading (Pat01: ~3300)

# index in the level table 0x16CF00 / character (0x16CF48: 0 ara 1 leg 2 gim 3 gan 4 sam
# 5 fro ...) by path (0x15AF38: wizardPath gan, kingPath ara, hobbitPath sam).
case "$(echo "$LEVEL" | tr A-Z a-z)" in
  hel01) IDX=0  CH=3 ;;  pat01) IDX=1  CH=0 ;;  pat03) IDX=2  CH=0 ;;  min02) IDX=3  CH=0 ;;
  pel02) IDX=4  CH=0 ;;  bla01) IDX=5  CH=0 ;;  ise01) IDX=6  CH=3 ;;  min00) IDX=7  CH=3 ;;
  min04) IDX=8  CH=3 ;;  osg01) IDX=9  CH=4 ;;  she01) IDX=10 CH=4 ;;  cir00) IDX=11 CH=4 ;;
  cra01) IDX=12 CH=4 ;;  cir01) IDX=14 CH=4 ;;  pat02) IDX=15 CH=0 ;;  pal01) IDX=16 CH=0 ;;
  pal02) IDX=17 CH=0 ;;
  *) echo "unknown level $LEVEL"; exit 2 ;;
esac
CH="${CHAR:-$CH}"
LC="$(echo "$LEVEL" | tr A-Z a-z)"
TEST_NAME="level_${LC}$([[ "${SOAK:-0}" == 1 ]] && echo _soak)"

# Hel01 is the prologue itself (New Game loads it): no route call; calling the route
# while the prologue's movie still plays faults at 0x11E5C0 (sweep-qa1, Hel01).
# ROTK_CALL_AT numbers are hex (idx 10 written as "10" was Pal01 = 0x10, 12+ out of range).
ROUTE="$ROUTE_AT:poke:16D584:$CH,$ROUTE_AT:9D770/$(printf %X "$IDX"),$ROUTE_AT:9C8A0/0"
[[ $IDX == 0 ]] && ROUTE="" LOAD_FRAMES=200
START_PLAY=$((ROUTE_AT + LOAD_FRAMES))
END="${END_AT:-$((START_PLAY + PLAY))}"   # END_AT: probe runs (stop early, see EXTRA_SHOTS)
PAD="$(mktemp -t rotk_level_pad)"
{
  echo "# generated by level_smoke.sh $LEVEL"
  echo "1100 press START"
  # one 600-frame cycle: run forward, attack combos, turn, jump/parry, run back
  for ((f = ROUTE_AT + 200; f < END; f += 600)); do
    echo "$f stick L 0 1 150"
    echo "$((f + 40)) press X"; echo "$((f + 80)) press X"; echo "$((f + 120)) press Y"
    echo "$((f + 160)) stick L 1 0.3 90"
    echo "$((f + 260)) press A"; echo "$((f + 300)) press B"; echo "$((f + 330)) hold RT 60"
    echo "$((f + 350)) press X"
    echo "$((f + 400)) stick L -0.6 -1 150"
    echo "$((f + 450)) press Y"; echo "$((f + 520)) press X"
    echo "$((f + 560)) stick R 1 0 30"
  done
} > "$PAD"

# End pairs: (END-300, END-30) and (END-1500, END-1230). A mission restart (fail menu ->
# Try Again -> reload) can make one pair two static frames (sweep-qa2 Pal01/Pal02); the other
# pair then proves input still reaches the game.
SHOTS="$((START_PLAY + PLAY / 2)),$((END - 1500)),$((END - 1230)),$((END - 300)),$((END - 30))"
[[ "${SOAK:-0}" == 1 ]] && SHOTS="$SHOTS,$((START_PLAY + 600))"
SHOTS="$SHOTS${EXTRA_SHOTS:+,$EXTRA_SHOTS}"
# Soak: sample RSS / CPU time / frame every 10 s (R-T9) -> $RUN/soak.tsv, judged below.
[[ "${SOAK:-0}" == 1 ]] && export RUN_MONITOR="python3 -I $TESTS_DIR/scripts/soak_monitor.py sample"
RUN_TIMEOUT="${RUN_TIMEOUT:-$(( END / 25 + 180 ))}" run_game "$TEST_NAME" \
  ROTK_PAD_SCRIPT="$PAD" ROTK_SHOT_FRAMES="$SHOTS" ROTK_EXIT_AFTER="$END" \
  ${ROUTE:+"ROTK_CALL_AT=$ROUTE"}
cp "$PAD" "$RUN/pad.txt"; rm -f "$PAD"
assert_exit0
assert_no_fatal
[[ -n $ROUTE ]] && assert_log "ROTK_CALL_AT 0009C8A0 returned" "route call did not run"
SEMANTIC=$((SEMANTIC + 1))
python3 -I "$TESTS_DIR/scripts/level_check.py" "$RUN" "$LEVEL" 50 $((PLAY * 2 / 3)) || fail "level $LEVEL not in gameplay"
assert_any_frames_differ $((END - 300)) $((END - 30)) $((END - 1500)) $((END - 1230))
if [[ "${SOAK:-0}" == 1 ]]; then
  SEMANTIC=$((SEMANTIC + 1))
  python3 -I "$TESTS_DIR/scripts/soak_monitor.py" report "$RUN" $((START_PLAY + 600)) || fail "soak: memory grows (soak_monitor)"
fi
grep -h -m1 -E "FATAL|unhandled guest exception" "${LOGS[@]}" 2>/dev/null | cut -c1-200 | sed 's/^/  first fault: /'
finish
