#!/bin/bash
# Frame-time check of a fight scene (60 fps gate: <= 1 % of frames over 16.7 ms busy).
#   tests/scripts/fps_check.sh [Level] [gameplay_frames] [VAR=value ...]
#   tests/scripts/fps_check.sh Hel01 3600                         # prologue fight, scale 1, 4:3
#   tests/scripts/fps_check.sh Hel01 3600 ROTK_RENDER_SCALE=4 ROTK_WIDESCREEN=1
# Hel01 = the Helm's Deep prologue (the fight with many enemies and fire; New Game loads it,
# ROTK_SKIP_MOVIES=1 brings it up at ~frame 240). Other levels: the scene-select route of
# level_smoke.sh (ROUTE_AT 1600 with movies skipped). Scripted input: run, attack combos, turn.
# The D3D HLE writes one line per Swap (ROTK_FRAME_LOG); tests/scripts/frame_stats.py
# measures busy time (frame minus vblank waits) over the gameplay window.
# PAUSE=1: press START at the end and shoot the pause menu (frame END+90).
# MAX_OVER (default 1.0 %), BUDGET (16.7 ms). MIN_FPS: average presented fps (default 59 with
# ROTK_FPS60=1, the .app's 60 fps mode; the original game runs at 30).
#   tests/scripts/fps_check.sh Hel01 2400 ROTK_FPS60=1 ROTK_RENDER_SCALE=4 ROTK_WIDESCREEN=1   # the .app
#   MIN_FPS=110 BUDGET=8.4 tests/scripts/fps_check.sh Hel01 4800 ROTK_FPS60=1 ROTK_FPS=120  # ProMotion
# Every run also checks that game time keeps wall speed (the fps.cpp report).
source "$(dirname "$0")/../lib.sh"
LEVEL="${1:-Hel01}"; shift || true
PLAY="${1:-3600}"; [[ $# -gt 0 && "$1" != *=* ]] && shift
case "$(echo "$LEVEL" | tr A-Z a-z)" in
  hel01) IDX=0  CH=3 ;;  pat01) IDX=1  CH=0 ;;  pat03) IDX=2  CH=0 ;;  min02) IDX=3  CH=0 ;;
  pel02) IDX=4  CH=0 ;;  bla01) IDX=5  CH=0 ;;  ise01) IDX=6  CH=3 ;;  min00) IDX=7  CH=3 ;;
  min04) IDX=8  CH=3 ;;  osg01) IDX=9  CH=4 ;;  she01) IDX=10 CH=4 ;;  cir00) IDX=11 CH=4 ;;
  cra01) IDX=12 CH=4 ;;  cir01) IDX=14 CH=4 ;;  pat02) IDX=15 CH=0 ;;  pal01) IDX=16 CH=0 ;;
  pal02) IDX=17 CH=0 ;;
  *) echo "unknown level $LEVEL"; exit 2 ;;
esac
LC="$(echo "$LEVEL" | tr A-Z a-z)"
TEST_NAME="fps_${LC}"
ROUTE_AT="${ROUTE_AT:-1600}"
if [[ $IDX == 0 ]]; then
  ROUTE=""; START_PLAY="${START_PLAY:-600}"
else
  ROUTE="$ROUTE_AT:poke:16D584:$CH,$ROUTE_AT:9D770/$(printf %X "$IDX"),$ROUTE_AT:9C8A0/0"
  START_PLAY="${START_PLAY:-$((ROUTE_AT + ${LOAD_FRAMES:-1200}))}"
fi
END=$((START_PLAY + PLAY))
if [[ -z "${MIN_FPS:-}" ]]; then MIN_FPS=0; [[ " $* " == *" ROTK_FPS60=1 "* ]] && MIN_FPS=59; fi
PAD="$(mktemp -t rotk_fps_pad)"
{
  echo "# generated by fps_check.sh $LEVEL"
  for ((f = START_PLAY - 300; f < END; f += 600)); do
    echo "$f stick L 0 1 150"
    echo "$((f + 40)) press X"; echo "$((f + 80)) press X"; echo "$((f + 120)) press Y"
    echo "$((f + 160)) stick L 1 0.3 90"
    echo "$((f + 260)) press X"; echo "$((f + 300)) press B"; echo "$((f + 330)) hold RT 60"
    echo "$((f + 350)) press X"
    echo "$((f + 400)) stick L -0.6 -1 150"
    echo "$((f + 450)) press Y"; echo "$((f + 520)) press X"
    echo "$((f + 560)) stick R 1 0 30"
  done
  [[ "${PAUSE:-0}" == 1 ]] && echo "$((END + 10)) press START"
} | sort -n -s -k1,1 > "$PAD"   # the pad script needs frames in order (START after the last cycle)
LAST=$END; [[ "${PAUSE:-0}" == 1 ]] && LAST=$((END + 100))
SHOTS="$((START_PLAY + PLAY / 2)),$((END - 30))"; [[ "${PAUSE:-0}" == 1 ]] && SHOTS="$SHOTS,$((END + 90))"
RUN_TIMEOUT="${RUN_TIMEOUT:-$(( LAST / 12 + 240 ))}" run_game "$TEST_NAME" \
  ROTK_SKIP_MOVIES=1 ROTK_PAD_SCRIPT="$PAD" ROTK_SHOT_FRAMES="$SHOTS" ROTK_EXIT_AFTER="$LAST" \
  ROTK_FRAME_LOG=frames.tsv ${ROUTE:+"ROTK_CALL_AT=$ROUTE"} "$@"
cp "$PAD" "$RUN/pad.txt"; rm -f "$PAD"
assert_exit0
assert_no_fatal
[[ -n $ROUTE ]] && assert_log "ROTK_CALL_AT 0009C8A0 returned" "route call did not run"
assert_frames_differ $((START_PLAY + PLAY / 2)) $((END - 30))
SEMANTIC=$((SEMANTIC + 1))
python3 -I "$TESTS_DIR/scripts/frame_stats.py" "$RUN/frames.tsv" $((START_PLAY + 300)) "$END" \
  "${BUDGET:-16.7}" "${MAX_OVER:-1.0}" "$MIN_FPS" | tee "$RUN/fps.txt"
[[ ${PIPESTATUS[0]} == 0 ]] || fail "more than ${MAX_OVER:-1.0} % of frames over ${BUDGET:-16.7} ms busy, or under $MIN_FPS fps"
# Game time runs at wall speed (src/polish/fps.cpp "fps: … game time x<r>" every 10 s; the first
# window holds the load): every later window within 10 %. ROTK_FPS=120 needs the line.
SEMANTIC=$((SEMANTIC + 1))
rates=$(grep -h -oE "game time x[0-9.]+" "${LOGS[@]}" 2>/dev/null | tail -n +2 | sed 's/game time x//')
echo "  game time / wall time: $(echo $rates)"
if [[ -z "$rates" ]]; then
  [[ " $* " == *" ROTK_FPS=120 "* ]] && fail "no 'game time' report under ROTK_FPS=120"
else
  for r in $rates; do
    awk -v r="$r" 'BEGIN { exit !(r >= 0.9 && r <= 1.1) }' || fail "game time x$r of wall time (want 0.9..1.1)"
  done
fi
finish
