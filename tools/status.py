#!/usr/bin/env python3
"""Builds STATUS.md from docs/status/<role>.md (RULES R-P2: nobody edits STATUS.md by hand;
HP2 had 6 merge conflicts in a shared STATUS.md). Each role file starts with fields:

  role: Render
  branch: claude/render-xyz
  ready: yes|no            (integrate.sh --all-ready merges the "yes" ones)
  works: <one line, with evidence: test / log / screenshot>
  next: <one line>
  blockers: <one line or ->
  not verified: <one line>

then free text / a dated log. Requests to another role: docs/requests/<from>-to-<to>-<date>.md.

  tools/status.py           write STATUS.md
  tools/status.py --check   exit 1 if STATUS.md is stale (CI/integrate)
"""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIELDS = ("role", "branch", "ready", "works", "next", "blockers", "not verified")


def parse(path):
    d = {}
    for line in open(path, encoding="utf-8"):
        k, _, v = line.partition(":")
        if k.strip().lower() in FIELDS and k.strip().lower() not in d:
            d[k.strip().lower()] = v.strip()
    d.setdefault("role", os.path.basename(path)[:-3])
    return d


def build():
    rows = [parse(p) for p in sorted(glob.glob(os.path.join(ROOT, "docs", "status", "*.md")))]
    reqs = sorted(os.path.basename(p) for p in glob.glob(os.path.join(ROOT, "docs", "requests", "*.md"))
                  if not p.endswith("README.md"))
    out = ["# STATUS — generated by tools/status.py from docs/status/*.md; do not edit", "",
           "| role | branch | ready | works | next | blockers | not verified |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append("| " + " | ".join(r.get(f, "").replace("|", "/") for f in FIELDS) + " |")
    out += ["", "## Open requests (docs/requests/)", ""] + ([f"- {r}" for r in reqs] or ["- none"]) + [""]
    return "\n".join(out)


def main():
    text = build()
    path = os.path.join(ROOT, "STATUS.md")
    if "--check" in sys.argv:
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        sys.exit(0 if old == text else 1)
    open(path, "w", encoding="utf-8").write(text)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
